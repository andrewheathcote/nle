"""Verify and time the exported ONNX flow.

Verification is against cases generated by the R port (`flow/scripts/onnx_cases.R`),
which is the reference implementation the golden vectors validate. Agreement is
expected at double precision; the only permitted difference is out-of-box rows,
where the port returns -Inf and the graph returns the documented floor.

    python flow/scripts/onnx_check.py <model.onnx> <cases.csv> [lan.onnx]

A second ONNX model (e.g. a published LAN) is timed alongside if given, which is
the only speed comparison between the two that is not implementation-bound:
same runtime, same machine, same call shape.
"""

import sys
import time

import numpy as np
import onnxruntime as ort

COLS = ["v", "a", "t0", "s", "Z", "SZ", "sv", "st0", "rt", "choice"]


def sess(path):
    o = ort.SessionOptions()
    o.intra_op_num_threads = 1          # one core, so the numbers are comparable
    o.inter_op_num_threads = 1
    return ort.InferenceSession(path, o, providers=["CPUExecutionProvider"])


def bench(s, x, reps=20):
    name = s.get_inputs()[0].name
    s.run(None, {name: x})
    t = time.perf_counter()
    for _ in range(reps):
        s.run(None, {name: x})
    return (time.perf_counter() - t) / reps * 1000 * 1000 / len(x)


def main(model, cases, lan=None):
    d = np.genfromtxt(cases, delimiter=",", names=True)
    X = np.column_stack([d[c] for c in COLS]).astype(np.float64)
    ref = d["logp"]
    s = sess(model)
    got = s.run(None, {s.get_inputs()[0].name: X})[0]

    fin = np.isfinite(ref) & np.isfinite(got)
    err = np.abs(got[fin] - ref[fin])
    print(f"cases {len(ref)}, in-box {int(fin.sum())}")
    print(f"  max |diff| vs R port {err.max():.3e}   median {np.median(err):.3e}")
    oob = ~np.isfinite(ref)
    if oob.any():
        print(f"  out-of-box rows {int(oob.sum())}: port -Inf, graph "
              f"{np.unique(np.round(got[oob], 6))} (the documented floor)")
    assert err.max() < 1e-8, "ONNX graph disagrees with the R port"

    n = 1000
    rows = np.tile(X[fin][:1], (n, 1))
    rows[:, 8] = np.random.default_rng(1).uniform(rows[0, 8] * 0.7, rows[0, 8] * 2.0, n)
    ms = bench(s, rows)
    print(f"\nspeed, one core, ms per 1000 trials\n  our flow (ONNX)   {ms:8.2f}")
    if lan:
        sl = sess(lan)
        i0 = sl.get_inputs()[0]
        shp = i0.shape
        # The published LANs are exported with a RANK-1 signature -- one trial
        # per call, shape [k] -- and HSSM batches outside by converting the graph
        # rather than calling onnxruntime per trial. So a batched comparison is
        # not available; this times what the file itself supports, which is
        # call-overhead dominated and must be labelled as such.
        if len(shp) == 1:
            k = int(shp[0])
            x1 = np.zeros(k, dtype=np.float32)
            x1[:5] = [1.0, 0.8, 0.5, 0.3, 0.05]                # v, a, z, t, st
            x1[-1] = 1.0                                       # choice
            name = i0.name
            sl.run(None, {name: x1})
            t = time.perf_counter()
            for r in range(n):
                x1[-2] = rows[r, 8]
                sl.run(None, {name: x1})
            per1000 = (time.perf_counter() - t) / n * 1000 * 1000
            print(f"  LAN      (ONNX)   {per1000:8.2f}   [rank-1 signature: {n} "
                  f"single-trial calls, call overhead dominated -- NOT comparable]")
        else:
            k = int(shp[1])
            xl = np.zeros((n, k), dtype=np.float32)
            xl[:, 0], xl[:, 1], xl[:, 2] = 1.0, 0.8, 0.5
            if k >= 5:
                xl[:, 3], xl[:, 4] = 0.3, 0.05
            xl[:, -2] = rows[:, 8]
            xl[:, -1] = 1.0
            print(f"  LAN      (ONNX)   {bench(sl, xl):8.2f}   [{k} inputs, batched]")


if __name__ == "__main__":
    main(*sys.argv[1:])
